static int g_failures = 0;
#define EXPECT_TRUE(cond) do { if (!(cond)) { std::cerr << "FAILED: " #cond " at line " << __LINE__ << std::endl; g_failures++; } } while (0)

using namespace riftwii;

// Made with tools outside the build (Python, standard DSA signing) for this
// test only: a digest, its signature by the key's private value x with the
// key's own generator (kSig), 2^x mod p (the public value that would belong
// to x), and a control key with a proper generator h of order q, its public
// value h^x and a signature with it (kSigH), which must verify.
