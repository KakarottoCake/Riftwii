static CtgpDsaKey test_key() {
    CtgpDsaKey k;
    std::memcpy(k.p, kTestP, 64);
    std::memcpy(k.q, kTestQ, 20);
    std::memcpy(k.g, kTestG, 64);
    std::memcpy(k.y, kTestY, 64);
    return k;
}

template <std::size_t N>
static CtgpBytes vec(const std::uint8_t (&a)[N]) { return CtgpBytes(a, a + N); }

static void test_core_roles() {
    std::array<std::uint8_t, 20> boot{}, boat{}, beat{};
    boot[0] = 1;
    boat[0] = 2;
    beat[0] = 3;
    const auto hashes = CtgpHashList::unverified_for_tests({
        {"/debug/bigfile1.big", boot}, {"/debug/bigfile7.big", boat}, {"/debug/bigfile6.big", beat}});
    EXPECT_TRUE(ctgp_core_digest_matches(hashes, "BOOT.BIN", boot));
    EXPECT_TRUE(ctgp_core_digest_matches(hashes, "BOAT.BIN", boat));
    EXPECT_TRUE(ctgp_core_digest_matches(hashes, "BEAT.BIN", beat));
    EXPECT_TRUE(!ctgp_core_digest_matches(hashes, "BOOT.BIN", boat));
    EXPECT_TRUE(!ctgp_core_digest_matches(hashes, "BOAT.BIN", beat));
    EXPECT_TRUE(!ctgp_core_digest_matches(hashes, "BEAT.BIN", boot));
    EXPECT_TRUE(!ctgp_core_digest_matches(hashes, "OTHER.BIN", boot));
}

int main() {
    test_core_roles();
    const CtgpDsaKey key = test_key();
    std::string error;
    CtgpHashList list;
    const auto good = vec(kTestList);
    EXPECT_TRUE(ctgp_load_hash_list(good, "TEST", 0x01020304, list, error, &key));
    EXPECT_TRUE(list.file_count() == 2);
    std::array<std::uint8_t, 20> d{};
    EXPECT_TRUE(list.find("/A/one.bin", d) && std::memcmp(d.data(), kDigestOne, 20) == 0);
    EXPECT_TRUE(list.find("/two.bin", d) && std::memcmp(d.data(), kDigestTwo, 20) == 0);
    EXPECT_TRUE(!list.find("/A/two.bin", d));
    EXPECT_TRUE(!list.find("/A", d));          // a directory has no digest
    EXPECT_TRUE(!list.find("/missing", d));
    EXPECT_TRUE(!list.find("/A/ONE.BIN", d));  // exact names only

    // CTGP's own key does not accept a list signed with the test key
    CtgpHashList other;
    EXPECT_TRUE(!ctgp_load_hash_list(good, "TEST", 0x01020304, other, error));
    EXPECT_TRUE(error.find("signature") != std::string::npos);

    // The channel signs only the first 20 bytes, so relabelling the name
    // and version keeps a valid signature. The body/version binding must
    // still refuse this for CORE, whose fixed addresses the launch relies on.
    // A CTGPR list is accepted on its signature when its label is the version
    // PACKAGES.BIN names (a CTGPR update), and refused when it is not.
    auto relabelled_as = [&](const char* name, std::uint32_t label) {
        auto relabelled = good;
        std::memset(relabelled.data() + 0x20, 0, 8);
        std::memcpy(relabelled.data() + 0x20, name, std::strlen(name));
        for (unsigned i = 0; i < 4; ++i) relabelled[0x28 + i] = static_cast<std::uint8_t>(label >> (24 - 8 * i));
        return relabelled;
    };
    EXPECT_TRUE(!ctgp_load_hash_list(relabelled_as("CORE", 0x01030412u), "CORE", 0x01030412u, other, error, &key));
    EXPECT_TRUE(error.find("known reference") != std::string::npos);
    {
        CtgpHashList update;
        EXPECT_TRUE(ctgp_load_hash_list(relabelled_as("CTGPR", 0x01031200u), "CTGPR", 0x01031200u, update, error, &key));
        EXPECT_TRUE(update.file_count() == 2);
        // its label must still be PACKAGES.BIN's version
        EXPECT_TRUE(!ctgp_load_hash_list(relabelled_as("CTGPR", 0x01031199u), "CTGPR", 0x01031200u, update, error, &key));
        EXPECT_TRUE(error.find("another version") != std::string::npos);
        // and its signature must verify
        auto forged = relabelled_as("CTGPR", 0x01031200u);
        forged[0x34] ^= 0x01;
        EXPECT_TRUE(!ctgp_load_hash_list(forged, "CTGPR", 0x01031200u, update, error, &key));
    }

    EXPECT_TRUE(ctgp_has_hash_reference("CORE", 0x01030412));
    // Both PACKAGES.BIN CTGPR builds (1192 and 1196) bind to the one CTGPR.HSH
    // body, since CTGP did not re-version the list between them.
    EXPECT_TRUE(ctgp_has_hash_reference("CTGPR", 0x01031192));
    EXPECT_TRUE(ctgp_has_hash_reference("CTGPR", 0x01031196));
    EXPECT_TRUE(!ctgp_has_hash_reference("CORE", 0x01030413));

    // The fix for the 1196 card: a list whose own version label (0x28) differs
    // from the PACKAGES.BIN version still loads when its body matches the signed
    // reference. A real card has PACKAGES.BIN CTGPR 0x01031196 but a CTGPR.HSH
    // still labelled 0x01031192. The reference is supplied here because the real
    // list body is CTGP data we do not ship; production uses the built-in
    // CTGPR/CORE references keyed on the PACKAGES.BIN version.
    {
        const Sha1Digest bd = sha1(good.data() + 0x60, good.size() - 0x60);
        std::array<std::uint8_t, 20> body{};
        std::memcpy(body.data(), bd.data(), 20);
        auto relabelled = good;
        const std::uint32_t label = 0x01031192u;  // the card's CTGPR.HSH 0x28 label
        for (unsigned i = 0; i < 4; ++i) relabelled[0x28 + i] = static_cast<std::uint8_t>(label >> (24 - 8 * i));
        // label (0x01031192) != requested PACKAGES.BIN version (0x01031196), but
        // the body matches the reference, so the list is accepted.
        CtgpHashList ok_list;
        EXPECT_TRUE(ctgp_load_hash_list(relabelled, "TEST", 0x01031196u, ok_list, error, &key, &body));
        EXPECT_TRUE(ok_list.file_count() == 2);
        // A relabelled older list whose body is not the reference is still
        // refused, label and version mismatch and all.
        auto wrong = body;
        wrong[0] ^= 0x01;
        CtgpHashList refused;
        EXPECT_TRUE(!ctgp_load_hash_list(relabelled, "TEST", 0x01031196u, refused, error, &key, &wrong));
    }

    // another package, another version
    EXPECT_TRUE(!ctgp_load_hash_list(good, "OTHER", 0x01020304, other, error, &key));
    EXPECT_TRUE(!ctgp_load_hash_list(good, "TEST", 0x01020305, other, error, &key));
    EXPECT_TRUE(!ctgp_load_hash_list(vec(kTestListOtherName), "TEST", 0x01020304, other, error, &key));
    EXPECT_TRUE(!ctgp_load_hash_list(vec(kTestListOtherVersion), "TEST", 0x01020304, other, error, &key));
    // a size field that is not the file's size (validly signed)
    EXPECT_TRUE(!ctgp_load_hash_list(vec(kTestListBadSize), "TEST", 0x01020304, other, error, &key));
    // the part of the body digest the signature does not cover, and the body itself
    for (std::size_t at : {std::size_t(20), std::size_t(31), std::size_t(0x60), good.size() - 1, good.size() - 25}) {
        auto bad = good;
        bad[at] ^= 0x01;
        EXPECT_TRUE(!ctgp_load_hash_list(bad, "TEST", 0x01020304, other, error, &key));
    }
    // the covered header bytes and the signature
    for (std::size_t at : {std::size_t(0), std::size_t(5), std::size_t(10), std::size_t(15), std::size_t(19), std::size_t(0x34), std::size_t(0x40)}) {
        auto bad = good;
        bad[at] ^= 0x01;
        EXPECT_TRUE(!ctgp_load_hash_list(bad, "TEST", 0x01020304, other, error, &key));
    }
    // truncated, empty, an oversize signature length
    EXPECT_TRUE(!ctgp_load_hash_list(CtgpBytes(good.begin(), good.begin() + 0x50), "TEST", 0x01020304, other, error, &key));
    EXPECT_TRUE(!ctgp_load_hash_list(CtgpBytes(), "TEST", 0x01020304, other, error, &key));
    auto longsig = good;
    longsig[0x2F] = 0x31;
    EXPECT_TRUE(!ctgp_load_hash_list(longsig, "TEST", 0x01020304, other, error, &key));
    // a name longer than eight characters cannot be a package
    EXPECT_TRUE(!ctgp_load_hash_list(good, "TOOLONGNAME", 0x01020304, other, error, &key));

    // Directly loaded track hashes need the channel's signed debug name.
    const CtgpBytes tracks(255 * 20, 0x5A);
    const auto tracks_digest = sha1(tracks.data(), tracks.size());
    const auto track_list = CtgpHashList::unverified_for_tests({{"/debug/smallfile.sml", tracks_digest}});
    EXPECT_TRUE(track_list.matches_digest("/debug/smallfile.sml", tracks_digest));
    auto changed_tracks = tracks;
    changed_tracks[100] ^= 1;
    EXPECT_TRUE(!track_list.matches_digest("/debug/smallfile.sml", sha1(changed_tracks.data(), changed_tracks.size())));
    EXPECT_TRUE(!track_list.matches_digest("/deyazhashes.hsh", tracks_digest));

    // Membership by digest (not by name): the native launch confirms directly
    // placed loader code this way, since it does not know the names CORE.HSH
    // gives those files. The digests of the verified list's two files are found;
    // a digest with one byte flipped is not.
    std::array<std::uint8_t, 20> probe{};
    std::memcpy(probe.data(), kDigestOne, 20);
    EXPECT_TRUE(list.contains_digest(probe));
    std::memcpy(probe.data(), kDigestTwo, 20);
    EXPECT_TRUE(list.contains_digest(probe));
    probe[0] ^= 0x01;
    EXPECT_TRUE(!list.contains_digest(probe));

    // Three blobs whose SHA-1s are in a (synthetic) list pass; flipping one byte
    // of one blob makes its digest absent, so that one fails.
    const std::vector<std::uint8_t> blob_a = {'c', 't', 'g', 'p', 'B', 'O', 'O', 'T'};
    const std::vector<std::uint8_t> blob_b = {'c', 't', 'g', 'p', 'B', 'O', 'A', 'T'};
    const std::vector<std::uint8_t> blob_c = {'c', 't', 'g', 'p', 'B', 'E', 'A', 'T'};
    std::map<std::string, std::array<std::uint8_t, 20>> code_digests;
    code_digests["/PACKAGES/CORE/BOOT.BIN"] = sha1(blob_a.data(), blob_a.size());
    code_digests["/PACKAGES/CORE/BOAT.BIN"] = sha1(blob_b.data(), blob_b.size());
    code_digests["/PACKAGES/CORE/BEAT.BIN"] = sha1(blob_c.data(), blob_c.size());
    const CtgpHashList core = CtgpHashList::unverified_for_tests(code_digests);
    EXPECT_TRUE(core.contains_digest(sha1(blob_a.data(), blob_a.size())));
    EXPECT_TRUE(core.contains_digest(sha1(blob_b.data(), blob_b.size())));
    EXPECT_TRUE(core.contains_digest(sha1(blob_c.data(), blob_c.size())));
    std::vector<std::uint8_t> tampered = blob_b;
    tampered[0] ^= 0x01;
    EXPECT_TRUE(!core.contains_digest(sha1(tampered.data(), tampered.size())));

    if (g_failures) {
        std::cerr << g_failures << " failures" << std::endl;
        return 1;
    }
    std::cout << "ctgphash tests passed" << std::endl;
    return 0;
}
