"""The Shift-JIS double-byte characters a Japanese GameCube memory card's
save names and comments are shown with (src/fs/gccard_text.cpp).

The table covers the rows the menu font keeps (tools/make_menu_font.py):
lead bytes 0x81-0x84 (symbols, full-width letters, kana, Greek, Cyrillic)
and 0x88-0x98 (the first-level kanji). Each row has 188 entries, one per
trail byte 0x40-0x7E then 0x80-0xFC, the Unicode code point or 0 where
the pair is not a character. Anything outside these rows is shown as '?',
as the menu font has no glyph for it either. 21 rows, 3948 entries,
7896 bytes in the DOL.

The mapping is Python's own shift_jis codec (JIS X 0208), the one
make_menu_font.py chose the font's characters with.

    python tools/make_sjis_table.py src/fs/sjis_table.inc
"""

import argparse

LEADS = list(range(0x81, 0x85)) + list(range(0x88, 0x99))
TRAILS = list(range(0x40, 0x7F)) + list(range(0x80, 0xFD))


def code_point(lead, trail):
    try:
        text = bytes([lead, trail]).decode("shift_jis")
    except UnicodeDecodeError:
        return 0
    return ord(text) if len(text) == 1 and ord(text) <= 0xFFFF else 0


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("out")
    args = ap.parse_args()

    lines = [
        "// SPDX-FileCopyrightText: 2026 RiftWii contributors",
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "// Generated by tools/make_sjis_table.py: Shift-JIS lead bytes",
        "// 0x81-0x84 and 0x88-0x98, 188 trail bytes each, as Unicode (0: none).",
    ]
    for lead in LEADS:
        values = [code_point(lead, trail) for trail in TRAILS]
        lines.append("// 0x%02X" % lead)
        for at in range(0, len(values), 12):
            lines.append(", ".join("0x%04X" % v for v in values[at:at + 12]) + ",")
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("%d rows written to %s" % (len(LEADS), args.out))


if __name__ == "__main__":
    main()
