"""Regenerate the compact decoder's differential corpus with zstd 1.5.7.

The repository vendors the decoder only. This uses the matching upstream
command-line compressor, without importing or inspecting compressor source.
Run in devkitPro MSYS2: python3 tools/rtzstd_corpus.py
"""

import argparse
import hashlib
import pathlib
import random
import subprocess
import tempfile


def make_data(kind, size):
    rng = random.Random(8878)
    if kind == "zero":
        return bytes(size)
    if kind == "random":
        return rng.randbytes(size)
    if kind == "text":
        words = b"RiftWii reads independent RVZ groups from the player's card. "
        return b"".join(
            words + str(rng.randrange(2000)).encode() + b"\n"
            for _ in range(size // len(words) + 1)
        )[:size]
    # Synthetic disc sectors: headers, repeated structures, biased literals,
    # incompressible islands and copies from far back in the same group.
    data = bytearray()
    while len(data) < size:
        sector = len(data) // 2048
        if sector % 7 == 0:
            block = rng.randbytes(2048)
        elif sector % 7 == 1:
            block = bytes(rng.randrange(32, 96) for _ in range(2048))
        elif sector % 7 == 2 and len(data) >= 65536:
            block = data[-65536:-63488]
        else:
            block = (b"RIFT" + sector.to_bytes(4, "big")) * 256
        data.extend(block)
    return bytes(data[:size])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--zstd", default="zstd")
    parser.add_argument("--output", type=pathlib.Path,
                        default=pathlib.Path("tests/fixtures/rtzstd"))
    args = parser.parse_args()
    version = subprocess.check_output([args.zstd, "--version"], text=True).strip()
    if "v1.5.7" not in version:
        parser.error("use the matching zstd 1.5.7 compressor; found " + version)
    args.output.mkdir(parents=True, exist_ok=True)
    cases = []
    for kind in ("zero", "random", "text", "disc"):
        for size in (1024, 32768, 131072, 524288):
            for level in (1, 3, 19, 22):
                cases.append((f"{kind}-{size}-l{level}", kind, size, level,
                              ["--zstd=wlog=10"] if size == 1024 else []))
    for size in (0, 1, 7, 31, 255, 256, 4095, 4096):
        cases.append((f"edge-{size}", "disc", size, 3, []))
    for level in (1, 3, 19, 22):
        cases.append((f"long-2097152-l{level}", "disc", 2097152, level,
                      ["--long=21", "--zstd=wlog=21"]))
    manifest = ["# zstd 1.5.7; name decoded-bytes sha256; generated by tools/rtzstd_corpus.py"]
    with tempfile.TemporaryDirectory(prefix="riftwii-rtzstd-") as temporary:
        source = pathlib.Path(temporary) / "source.bin"
        for index, (name, kind, size, level, options) in enumerate(cases):
            data = make_data(kind, size)
            source.write_bytes(data)
            # Alternate known/unknown content size and checksum presence.
            command = [args.zstd, "-q", "-f", "--ultra", f"-{level}"]
            command += ["--check" if index % 2 else "--no-check"]
            command += options
            if index % 3 == 0:
                command += ["--no-content-size"]
            command += [str(source), "-o", str(args.output / (name + ".zst"))]
            subprocess.run(command, check=True)
            manifest.append(f"{name}.zst {size} {hashlib.sha256(data).hexdigest()}")
    (args.output / "manifest.txt").write_text("\n".join(manifest) + "\n", encoding="utf-8")
    print(f"Generated {len(cases)} independent frames with {version}")


if __name__ == "__main__":
    main()
