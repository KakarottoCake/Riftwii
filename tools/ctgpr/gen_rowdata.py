"""Generate src/ctgpr/ctgprowdata.cpp from CTGP-R's row table (rows.bin).

The row table is CTGP-R's own, non-secret data ("CRT0" + a row count + 2570
rows of three big-endian game addresses + 54 region words). RiftWii's native
CTGP-R launch needs it to place CTGP over Mario Kart Wii, so it is baked into
the build instead of asking the player for a file on the card. The player's own
copy of CTGP-R on the SD card (blob.bin) stays the only input read at run time.

Run this once when the table changes and commit the generated .cpp:
    python3 -I tools/ctgpr/gen_rowdata.py <rows.bin> [out.cpp]
The default output is src/ctgpr/ctgprowdata.cpp.
"""
import os
import sys


def main() -> int:
    if len(sys.argv) < 2:
        sys.stderr.write("usage: gen_rowdata.py <rows.bin> [out.cpp]\n")
        return 2
    src = sys.argv[1]
    repo = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(repo, "src", "ctgpr", "ctgprowdata.cpp")
    with open(src, "rb") as f:
        data = f.read()
    if data[:4] != b"CRT0":
        sys.stderr.write("rows.bin does not start with CRT0\n")
        return 1
    lines = [
        "// SPDX-FileCopyrightText: 2026 RiftWii contributors",
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "// Generated by tools/ctgpr/gen_rowdata.py from CTGP-R's row table. Do not edit.",
        "// CTGP-R's own non-secret table of the game addresses its channel hooks.",
        '#include "riftwii/ctgptables.hpp"',
        "",
        "namespace riftwii {",
        "namespace {",
        "",
        "const unsigned char kCtgpRowData[] = {",
    ]
    for i in range(0, len(data), 16):
        chunk = data[i:i + 16]
        lines.append("    " + "".join("0x%02x," % b for b in chunk))
    lines += [
        "};",
        "",
        "}  // namespace",
        "",
        "const std::uint8_t* ctgp_embedded_row_table(std::size_t& size) {",
        "    size = sizeof kCtgpRowData;",
        "    return kCtgpRowData;",
        "}",
        "",
        "}  // namespace riftwii",
        "",
    ]
    with open(out, "w") as f:
        f.write("\n".join(lines))
    sys.stderr.write("wrote %s (%d bytes of row data)\n" % (out, len(data)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
