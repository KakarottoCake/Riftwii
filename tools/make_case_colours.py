"""The games whose case is not white, from GameTDB's database, for the
Home shelf's boxes (src/casecolour.cpp).

GameTDB (https://www.gametdb.com) gives a game's case colour as
<case color="rrggbb"/>; empty means the usual white case. Wii discs and
GameTDB's custom entries (mod distributions with IDs of their own, such
as Project M's RSBEPM) are kept; WiiWare, Virtual Console, channels and
GameCube discs never stand on the shelf. A colour that is not six hex
digits, or is white, is left out.

    python tools/make_case_colours.py wiitdb.xml src/casecolours.inc

wiitdb.xml is in https://www.gametdb.com/wiitdb.zip.
"""

import argparse
import re
import xml.etree.ElementTree as ET


def case_colour(game):
    case = game.find("case")
    colour = (case.get("color") if case is not None else None) or ""
    colour = colour.strip().lower()
    if not re.fullmatch(r"[0-9a-f]{6}", colour):
        return None
    if all(int(colour[i:i + 2], 16) >= 0xf0 for i in (0, 2, 4)):
        return None  # white: the shelf's own plastic
    return colour


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("wiitdb")
    parser.add_argument("out")
    args = parser.parse_args()
    root = ET.parse(args.wiitdb).getroot()
    version = root.find("WiiTDB").get("version", "")
    retail, custom = {}, {}
    for game in root.iter("game"):
        gid = (game.findtext("id") or "").strip().upper()
        kind = (game.findtext("type") or "").strip()
        if kind not in ("", "CUSTOM") or len(gid) != 6 or not gid.isalnum():
            continue
        colour = case_colour(game)
        if colour:
            (retail if kind == "" else custom).setdefault(gid, colour)
    # A custom entry never overrides the disc of the same ID.
    colours = dict(custom)
    colours.update(retail)
    entries = sorted(colours.items())
    with open(args.out, "w", encoding="ascii", newline="\n") as f:
        f.write("// SPDX-FileCopyrightText: 2026 RiftWii contributors\n")
        f.write("// SPDX-License-Identifier: GPL-3.0-or-later\n")
        f.write("// Generated by tools/make_case_colours.py from GameTDB's wiitdb.xml\n")
        f.write("// (https://www.gametdb.com), version %s: %d games.\n" % (version, len(entries)))
        for i in range(0, len(entries), 6):
            f.write(" ".join('"%s%s"' % e for e in entries[i:i + 6]) + "\n")
    print("%d games with a case that is not white (%d discs, %d custom)" %
          (len(entries), len(retail), len(entries) - len(retail)))


if __name__ == "__main__":
    main()
