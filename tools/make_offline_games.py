"""The games with no online play, from GameTDB's database, for the game
page's Online server row (src/data/offlinegames.cpp).

GameTDB (https://www.gametdb.com) lists each game's online features under
<wi-fi players="N"><feature>...</feature></wi-fi>. A game counts as having
no online play only when GameTDB says so plainly: no online players and
no feature that went through Nintendo Wi-Fi Connection (score, download,
wiimmfi). "online" alone is kept as online (Boom Blox's level sharing),
unless the only other feature is the Message Board (WiiConnect24: Wii
Sports Resort). Games GameTDB does not know, and its custom entries
(hacks, mod distributions), are left out: their row stays as it is.

Codes are the IDs' first four characters (game and region); a code is
listed only when every game with it has no online play. Most games come in
a few of the same regions, so the table stores each game's first three
characters once, with a byte whose bits say which of REGIONS it has (6 KiB
of MEM1 instead of 12); codes in other regions are listed whole.

    python tools/make_offline_games.py wiitdb.xml src/data/offlinegames.inc

wiitdb.xml is in https://www.gametdb.com/wiitdb.zip.
"""

import argparse
import xml.etree.ElementTree as ET

WFC_FEATURES = {"score", "download", "wiimmfi"}
# The regions with a bit each, in offlinegames.cpp's order.
REGIONS = "EPJXKDFY"


def has_online(game):
    wifi = game.find("wi-fi")
    if wifi is None:
        return False
    players = wifi.get("players", "0")
    if players.isdigit() and int(players) > 0:
        return True
    features = {f.text for f in wifi.findall("feature") if f.text}
    if features & WFC_FEATURES:
        return True
    return "online" in features and "messageboard" not in features


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("wiitdb")
    parser.add_argument("out")
    args = parser.parse_args()
    root = ET.parse(args.wiitdb).getroot()
    version = root.find("WiiTDB").get("version", "")
    offline, online = set(), set()
    for game in root.iter("game"):
        gid = (game.findtext("id") or "").strip()
        if (game.findtext("type") or "").strip() or len(gid) != 6 or not gid.isalnum():
            continue  # custom entries, WiiWare and Virtual Console
        (online if has_online(game) else offline).add(gid[:4].upper())
    codes = sorted(offline - online)
    write_table(args.out, version, codes)
    print("%d game codes with no online play (%d with online)" % (len(codes), len(online)))


def encode(codes):
    """(prefixes, others): sorted 3-character prefixes with their region
    bits, and the whole codes whose region has no bit."""
    masks = {}
    others = []
    for code in codes:
        if code[3] in REGIONS:
            masks[code[:3]] = masks.get(code[:3], 0) | (1 << REGIONS.index(code[3]))
        else:
            others.append(code)
    return sorted(masks.items()), sorted(others)


def decode(prefixes, others):
    codes = [p + REGIONS[bit] for p, mask in prefixes for bit in range(len(REGIONS)) if mask & (1 << bit)]
    return sorted(codes + others)


def write_table(out, version, codes):
    prefixes, others = encode(codes)
    if decode(prefixes, others) != sorted(codes):
        raise SystemExit("make_offline_games: the packed table does not give the codes back")
    with open(out, "w", encoding="ascii", newline="\n") as f:
        f.write("// SPDX-FileCopyrightText: 2026 RiftWii contributors\n")
        f.write("// SPDX-License-Identifier: GPL-3.0-or-later\n")
        f.write("// Generated by tools/make_offline_games.py from GameTDB's wiitdb.xml\n")
        f.write("// (https://www.gametdb.com), version %s: %d codes.\n" % (version, len(codes)))
        f.write("// Each game's first three characters and a byte of region bits (%s), sorted.\n" % REGIONS)
        f.write("const char kPrefixes[] =\n")
        for i in range(0, len(prefixes), 8):
            f.write(" ".join('"%s" "\\x%02x"' % (p, mask) for p, mask in prefixes[i:i + 8]) + "\n")
        f.write("    ;\n")
        f.write("// Whole codes in the other regions, sorted.\n")
        f.write("const char kOtherCodes[] =\n")
        for i in range(0, len(others), 12):
            f.write(" ".join('"%s"' % c for c in others[i:i + 12]) + "\n")
        f.write('    "";\n')


if __name__ == "__main__":
    main()
